import {writeFile} from 'node:fs/promises';

import {baseTheme, darkTheme, lightTheme} from '@sentry/scraps/theme';
import {format} from 'prettier';

const outputUrl = new URL('../src/styles/scraps-theme.css', import.meta.url);
const colorGroups = ['background', 'border', 'content', 'graphics'];

function toKebabCase(value) {
  return value.replaceAll(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function flattenValues(values, path = []) {
  return Object.entries(values).flatMap(([key, value]) => {
    const nextPath = [...path, toKebabCase(key)];
    return value !== null && typeof value === 'object'
      ? flattenValues(value, nextPath)
      : [[nextPath.join('-'), String(value)]];
  });
}

function declarations(entries) {
  return entries.map(([name, value]) => `  --scraps-${name}: ${value};`);
}

function themeAliases(entries, namespace) {
  return entries.map(([name]) => `  --${namespace}-${name}: var(--scraps-${name});`);
}

function colorThemeAliases(entries) {
  return entries.map(([name]) => {
    const utilityName = name.replace(/^border-/, '');
    return `  --color-${utilityName}: var(--scraps-${name});`;
  });
}

function fontSizeAliases(entries) {
  return entries.map(([name]) => {
    const size = name.replace('font-size-', '');
    return `  --text-size-${size}: var(--scraps-${name});`;
  });
}

function colorEntries(theme) {
  return colorGroups.flatMap(group => flattenValues(theme.tokens[group], [group]));
}

const baseEntries = [
  ...flattenValues(baseTheme.space, ['space']),
  ...flattenValues(baseTheme.radius, ['radius']),
  ...flattenValues(baseTheme.font.size, ['font-size']),
  ['font-weight-regular', baseTheme.font.weight.sans.regular],
  ['font-weight-medium', baseTheme.font.weight.sans.medium],
  ['font-family-sans', baseTheme.font.family.sans],
  ['font-family-mono', baseTheme.font.family.mono],
  ...flattenValues(baseTheme.font.lineHeight, ['line-height']),
].map(([name, value]) => [name, String(value)]);
const lightColorEntries = colorEntries(lightTheme);
const darkColorEntries = colorEntries(darkTheme);
const spaceEntries = flattenValues(baseTheme.space, ['space']);
const radiusEntries = flattenValues(baseTheme.radius, ['radius']);
const fontSizeEntries = flattenValues(baseTheme.font.size, ['font-size']);

const css = [
  '/* Generated by scripts/generate-scraps-theme.mjs. Do not edit. */',
  '',
  ':root {',
  ...declarations(baseEntries),
  ...declarations(lightColorEntries),
  '}',
  '',
  '@media (prefers-color-scheme: dark) {',
  '  :root {',
  ...declarations(darkColorEntries).map(line => `  ${line}`),
  '  }',
  '}',
  '',
  '@theme inline {',
  ...colorThemeAliases(lightColorEntries),
  '  --color-content-muted: var(--scraps-content-secondary);',
  ...themeAliases(spaceEntries, 'spacing'),
  '  /* Local extension: Scraps spacing currently stops at 3xl. */',
  '  --spacing-space-4xl: 48px;',
  ...themeAliases(radiusEntries, 'radius'),
  ...fontSizeAliases(fontSizeEntries),
  '  --font-weight-regular: var(--scraps-font-weight-regular);',
  '  --font-weight-medium: var(--scraps-font-weight-medium);',
  '  --font-sans: var(--scraps-font-family-sans);',
  '  --font-mono: var(--scraps-font-family-mono);',
  '  --leading-compressed: var(--scraps-line-height-compressed);',
  '  --leading-default: var(--scraps-line-height-default);',
  '  --leading-comfortable: var(--scraps-line-height-comfortable);',
  '}',
  '',
].join('\n');

await writeFile(
  outputUrl,
  await format(css, {parser: 'css', printWidth: 90, singleQuote: true})
);
